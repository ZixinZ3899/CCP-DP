#!/usr/bin/env python3
"""Generate paired Coverage x IDS stress-test clusters from fixed DNA centers.

For a fixed seed and cluster, the random streams are shared across coverage and
error-rate conditions. Thus 5x reads are a strict prefix of 10x reads, and
higher IDS levels are generated by increasing thresholds on the same random
numbers. This paired design reduces Monte Carlo noise without using truth at
reconstruction time.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
from pathlib import Path

BASES = "ACGT"


def read_sequences(path: Path) -> list[str]:
    lines = [x.strip().upper() for x in path.read_text().splitlines() if x.strip()]
    if not lines:
        raise ValueError(f"No sequences found: {path}")
    if any(x.startswith(">") for x in lines):
        records: list[str] = []
        current: list[str] = []
        for line in lines:
            if line.startswith(">"):
                if current:
                    records.append("".join(current))
                    current = []
            else:
                current.append(line)
        if current:
            records.append("".join(current))
        lines = records
    invalid = [(i + 1, s) for i, s in enumerate(lines) if set(s) - set(BASES)]
    if invalid:
        raise ValueError(f"Non-ACGT sequence at record {invalid[0][0]}")
    return lines


def stable_cluster_seed(seed: int, cluster_index: int) -> int:
    payload = f"coverage-ids-v2-paired:{seed}:{cluster_index}".encode()
    return int.from_bytes(hashlib.blake2b(payload, digest_size=8).digest(), "big")


def mutate(center: str, rng: random.Random, p_sub: float, p_ins: float,
           p_del: float) -> str:
    out: list[str] = []
    for base in center:
        u_del = rng.random()
        u_sub = rng.random()
        u_ins = rng.random()
        inserted = BASES[rng.randrange(4)]
        # Draw the possible substitution unconditionally.  Every source base
        # therefore consumes exactly the same random numbers at every error
        # rate, which makes higher IDS settings true threshold-coupled controls.
        base_index = BASES.index(base)
        substituted = BASES[(base_index + 1 + rng.randrange(3)) % 4]

        if u_del >= p_del:
            if u_sub < p_sub:
                out.append(substituted)
            else:
                out.append(base)

        # Insertion is an independent event after the source position. It may
        # co-occur with deletion, matching a standard IDS-channel simulation.
        if u_ins < p_ins:
            out.append(inserted)
    return "".join(out)


def generate_condition(centers: list[str], coverage: int, total_indel: float,
                       p_sub: float, seed: int, destination: Path,
                       separator: str) -> None:
    p_ins = total_indel / 2.0
    p_del = total_indel / 2.0
    destination.mkdir(parents=True, exist_ok=True)

    centers_path = destination / "Centers.txt"
    clusters_path = destination / "Clusters.txt"
    centers_path.write_text("\n".join(centers) + "\n")

    with clusters_path.open("w") as handle:
        for cluster_index, center in enumerate(centers):
            handle.write(separator + "\n")
            rng = random.Random(stable_cluster_seed(seed, cluster_index))
            for _ in range(coverage):
                handle.write(mutate(center, rng, p_sub, p_ins, p_del) + "\n")

    metadata = {
        "condition_id": (
            f"cov{coverage:02d}_indel{round(total_indel * 100):02d}_seed{seed}"
        ),
        "coverage": coverage,
        "total_indel": total_indel,
        "p_sub": p_sub,
        "p_ins": p_ins,
        "p_del": p_del,
        "seed": seed,
        "clusters": len(centers),
        "target_length": len(centers[0]),
        "separator": separator,
        "generator_version": "coverage-ids-v2-paired",
        "channel_definition": (
            "deletion per source base; substitution conditional on retention; "
            "independent single-base insertion after each source position"
        ),
    }
    (destination / "metadata.json").write_text(
        json.dumps(metadata, indent=2) + "\n"
    )


def parse_percent_list(text: str) -> list[float]:
    return [float(x) / 100.0 for x in text.split(",") if x.strip()]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--centers", required=True, type=Path)
    parser.add_argument("--outdir", required=True, type=Path)
    parser.add_argument("--coverage", default="5,10,15,20")
    parser.add_argument("--indel-pct", default="2,4,6,8,10")
    parser.add_argument("--sub-pct", default=2.0, type=float)
    parser.add_argument("--seeds", default="2026,2027,2028,2029,2030")
    parser.add_argument("--separator", default="===============================")
    parser.add_argument("--limit-centers", type=int, default=None)
    args = parser.parse_args()

    centers = read_sequences(args.centers)
    if args.limit_centers is not None:
        centers = centers[: args.limit_centers]
    lengths = {len(x) for x in centers}
    if len(lengths) != 1:
        raise ValueError(f"Centers must have one fixed length, got {sorted(lengths)}")

    coverages = [int(x) for x in args.coverage.split(",") if x.strip()]
    indels = parse_percent_list(args.indel_pct)
    seeds = [int(x) for x in args.seeds.split(",") if x.strip()]
    p_sub = args.sub_pct / 100.0

    if any(x <= 0 for x in coverages):
        raise ValueError("Coverage must be positive")
    if any(not 0 <= x < 1 for x in indels + [p_sub]):
        raise ValueError("All error probabilities must be in [0, 1)")

    total = len(coverages) * len(indels) * len(seeds)
    done = 0
    for coverage in coverages:
        for total_indel in indels:
            for seed in seeds:
                condition_id = (
                    f"cov{coverage:02d}_indel{round(total_indel * 100):02d}_seed{seed}"
                )
                generate_condition(
                    centers, coverage, total_indel, p_sub, seed,
                    args.outdir / condition_id, args.separator,
                )
                done += 1
                print(f"[{done:03d}/{total:03d}] {condition_id}")

    print(f"Generated {total} paired conditions in {args.outdir.resolve()}")


if __name__ == "__main__":
    main()
